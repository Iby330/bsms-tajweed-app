/** The header cartouche glyph for a surah, or null outside 1–114. */
export function surahHeaderGlyph(surah: number): string | null {
  const cp = SURAH_HEADER_CODEPOINTS[surah - 1];
  return cp ? String.fromCodePoint(cp) : null;
}
