import { seatDaggerAlif } from "@/lib/quran/text";

/** One word of the seeded Uthmani text, positioned in the Madani mushaf. */
export type QuranWord = {
  surah: number;
  ayah: number;
  position: number; // 1-based within the ayah
  text: string;
  glyph: string | null; // QCF v2 page-font character — the printed word itself
  isEnd: boolean;   // ayah-end marker (the numeral)
  page: number;
  line: number;
};

export type QuranWordRow = {
  surah_number: number;
  ayah_number: number;
  word_position: number;
  text_uthmani: string;
  code_v1: string | null;
  code_v2: string | null;
  is_end: boolean;
  page_number: number;
  line_number: number;
};

export type MushafLine = { line: number; words: QuranWord[] };
export type MushafPage = { page: number; lines: MushafLine[] };

export const wordKey = (w: Pick<QuranWord, "surah" | "ayah" | "position">): string =>
  `${w.surah}:${w.ayah}:${w.position}`;

/** A whole ayah — the key a mistake takes when it isn't pinned to one word.
 *  Two segments where wordKey has three, so the two can never collide. */
export const ayahKey = (w: Pick<QuranWord, "surah" | "ayah">): string =>
  `${w.surah}:${w.ayah}`;

/** The key a logged mistake lives under: the ayah when `position` is null
 *  (the reviewer tapped the ayah's end marker), the word otherwise. This is
 *  the single place that convention is decided — everything that stores or
 *  looks up a mark goes through it. */
export const markKey = (
  m: { surah: number; ayah: number; position: number | null },
): string => (m.position === null ? ayahKey(m) : wordKey({ ...m, position: m.position }));

// V1 (1405H) — the school's physical mushaf, confirmed by its own line
// breaks (Al-Ikhlas splits لم يلد / ولم يولد). Glyph edition must match
// the page fonts AND the seeded line data; never mix editions per word.
export const fromRow = (r: QuranWordRow): QuranWord => ({
  surah: r.surah_number, ayah: r.ayah_number, position: r.word_position,
  text: seatDaggerAlif(r.text_uthmani), glyph: r.code_v1, isEnd: r.is_end,
  page: r.page_number, line: r.line_number,
});

